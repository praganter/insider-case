export const messages: Record<Lang, Record<Key, string>> = { en, tr }

export type Translate = (key: Key, params?: Record<string, string | number>) => string

export const translator =
  (lang: Lang): Translate =>
  (key, params = {}) =>
    messages[lang][key].replace(/\{(\w+)\}/g, (_, p) => String(params[p] ?? `{${p}}`))

export const hasKey = (key: string): key is Key => key in en
